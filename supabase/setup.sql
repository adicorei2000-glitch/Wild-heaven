-- ---------------------------------------------------------------------
-- 2) BOOKINGS: xavfsizlik (RLS)
-- ---------------------------------------------------------------------
alter table public.bookings enable row level security;

drop policy if exists "bookings_select_own" on public.bookings;
create policy "bookings_select_own" on public.bookings
  for select to authenticated
  using (auth.uid() = user_id);

drop policy if exists "bookings_insert_own" on public.bookings;
create policy "bookings_insert_own" on public.bookings
  for insert to authenticated
  with check (auth.uid() = user_id);

drop policy if exists "bookings_delete_own" on public.bookings;
create policy "bookings_delete_own" on public.bookings
  for delete to authenticated
  using (auth.uid() = user_id);

-- ---------------------------------------------------------------------
-- 3) BOOKINGS: sanalar kesishmasin, chiqish kirishdan keyin bo'lsin
--    Chiqish kuni band hisoblanmaydi: [check_in, check_out)
-- ---------------------------------------------------------------------
alter table public.bookings drop constraint if exists bookings_no_overlap;
alter table public.bookings
  add constraint bookings_no_overlap
  exclude using gist (
    villa_id with =,
    daterange(check_in, check_out, '[)') with &&
  );

alter table public.bookings drop constraint if exists bookings_dates_valid;
alter table public.bookings
  add constraint bookings_dates_valid
  check (check_out > check_in);

-- ---------------------------------------------------------------------
-- 4) BOOKINGS: narx va villa nomi serverda hisoblanadi
-- ---------------------------------------------------------------------
create or replace function public.bookings_before_insert()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v public.villas%rowtype;
begin
  select * into v from public.villas where id = new.villa_id;

  if not found then
    raise exception 'Villa topilmadi' using errcode = 'P0002';
  end if;

  if new.guests > v.max_guests then
    raise exception 'Bu villa ko''pi bilan % mehmon uchun', v.max_guests
      using errcode = '22023';
  end if;

  -- 1 kun zaxira: foydalanuvchi vaqt mintaqasi UTC dan orqada bo'lishi mumkin
  if new.check_in < current_date - 1 then
    raise exception 'O''tgan sanaga bron qilib bo''lmaydi' using errcode = '22007';
  end if;

  new.villa_name  := v.name;
  new.total_price := (new.check_out - new.check_in) * v.price;
  return new;
end;
$$;

drop trigger if exists bookings_before_insert on public.bookings;
create trigger bookings_before_insert
  before insert on public.bookings
  for each row execute function public.bookings_before_insert();

-- ---------------------------------------------------------------------
-- 5) Band sanalar (faqat sanalar, kim bron qilgani ko'rinmaydi)
-- ---------------------------------------------------------------------
create or replace function public.get_booked_ranges(p_villa_id integer)
returns table (check_in date, check_out date)
language sql
stable
security definer
set search_path = public
as $$
  select b.check_in, b.check_out
  from public.bookings b
  where b.villa_id = p_villa_id
    and b.check_out >= current_date
  order by b.check_in;
$$;

revoke all on function public.get_booked_ranges(integer) from public;
grant execute on function public.get_booked_ranges(integer) to anon, authenticated;

